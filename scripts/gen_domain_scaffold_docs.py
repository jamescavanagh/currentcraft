"""Generate docs/contracts/DOMAIN_SCAFFOLD.md from the manifest and classes. --check fails if stale."""
import importlib, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
MANIFEST = ROOT / "docs/domain/domain_scaffold_manifest.json"
OUT = ROOT / "docs/contracts/DOMAIN_SCAFFOLD.md"


def render_rows(rows) -> str:
    """Pure formatting shared by generation and exact metadata regeneration."""
    lines = ["---", "title: Domain scaffold (generated)", "tags: [datamesh, generated]", "---", "",
             "# Domain scaffold (generated)", "",
             "Generated by `scripts/gen_domain_scaffold_docs.py`. Do not edit by hand. Design source: [DOMAIN_SCAFFOLD.md](../domain/DOMAIN_SCAFFOLD.md).",
             "", f"{len(rows)} historical names; `v1-proposal` implements capture (V1_DOMAIN.md); `p4-proposal` implements local and explicit-context invariants (P4_DESIGN_CONTRACTS.md). Neither grants operating authority.", "",
             "| Class | Module | Origin | Status | Note |", "| --- | --- | --- | --- | --- |"]
    for row in sorted(rows, key=lambda r: (r[1], r[0])):
        name, module, source, status, note = row
        lines.append(f"| `{name}` | `{module}` | {source} | `{status}` | {note} |")
    return "\n".join(lines) + "\n"


def render() -> str:
    entries = json.loads(MANIFEST.read_text())["entries"]
    rows = []
    for e in entries:
        cls = getattr(importlib.import_module(e["module"]), e["class_name"])
        assert cls.SCHEMA_STATUS in {"unreviewed-scaffold", "v1-proposal", "p4-proposal"}, e
        if cls.SCHEMA_STATUS == "unreviewed-scaffold":
            assert set(cls.model_fields) == {"entity_id", "definition_status"}, e
        rows.append((e["class_name"], e["module"], e["source"], cls.SCHEMA_STATUS, (cls.__doc__ or cls.NOTE).strip()))
    return render_rows(rows)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("OK: domain scaffold reference current" if ok else "STALE: run scripts/gen_domain_scaffold_docs.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
