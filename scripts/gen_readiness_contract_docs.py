"""Generate (or --check) the readiness contract docs: evaluation and release ladder (later grammar).

Self-contained helpers so the output depends only on these slices. JSON Schemas are not generated here yet.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from app.application import evaluation as EV  # noqa: E402
from app.application import ladder as LD  # noqa: E402

OUT = ROOT / "docs" / "contracts"
TARGET = "READINESS_CONTRACTS.md"
JUNK = ("typing.", "app.application.common.contracts.", "app.application.common.states.",
        "app.application.evaluation.contracts.", "app.application.ladder.contracts.")

SLICES = (("Evaluation harness", "architecture/EVALUATION.md", EV.SCHEMA_VERSION, EV.CONTRACTS),
          ("Release ladder", "domain/RELEASE_LADDER.md", LD.SCHEMA_VERSION, LD.CONTRACTS))


def _type(ann) -> str:
    if isinstance(ann, type):
        return ann.__name__
    s = str(ann)
    for junk in JUNK:
        s = s.replace(junk, "")
    s = s.replace("NoneType", "None")
    s = re.sub(r"<class '([\w.]+)'>", lambda m: m.group(1).split(".")[-1], s)
    return s if len(s) < 90 else s[:87] + "..."


def _default(f) -> str:
    if f.is_required():
        return "yes"
    if f.default_factory is not None:
        return f"no (`{f.default_factory.__name__}()`)"
    return "no" if f.default is None else f"no (`{f.default!r}`)"


def _rows(model) -> list[str]:
    return [f"| `{n}` | `{_type(f.annotation)}` | {_default(f)} | {(f.description or '').replace('|', '/')} |"
            for n, f in model.model_fields.items()]


def render() -> dict[str, str]:
    md = ["---", "title: Readiness contracts (generated)", "tags: [currentcraft, generated]", "---", "",
          "# Readiness contracts (generated)", "",
          "Generated by `scripts/gen_readiness_contract_docs.py`. Do not edit by hand: change the contract, then regenerate.",
          "CI fails when this file is stale. Design sources are linked per slice.", ""]
    for title, page, version, contracts in SLICES:
        md += [f"## {title}", "", f"Design source: [{page}](../{page}). Schema version: `{version}`.", ""]
        for m in contracts:
            md += [f"### `{m.__name__}`", "", (m.__doc__ or "").strip(), "",
                   "| Field | Type | Required | Description |", "| --- | --- | --- | --- |", *_rows(m), ""]
    return {TARGET: "\n".join(md)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    files, stale = render(), []
    for rel, text in files.items():
        path = OUT / rel
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if a.check:
        for rel in stale:
            print(f"STALE {rel}")
        print(f"{'OK' if not stale else 'FAIL'}: {len(files)} generated readiness docs, {len(stale)} stale")
        if stale:
            print("Run: python3 scripts/gen_readiness_contract_docs.py")
        return 1 if stale else 0
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
