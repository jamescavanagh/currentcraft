"""Generate (or --check) docs/contracts/PERSISTENCE_SCHEMA.md from the migrations (PostgreSQL 18 dialect)."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from app.infrastructure.persistence import MIGRATIONS, POSTGRES, render_ddl  # noqa: E402

OUT = ROOT / "docs" / "contracts" / "PERSISTENCE_SCHEMA.md"


def render() -> str:
    md = ["---", "title: Persistence schema (generated)", "tags: [datamesh, generated, persistence]", "---", "",
          "# Persistence schema (generated)", "",
          "Generated by `scripts/gen_persistence_docs.py` from `app.infrastructure.persistence.migrations`. Do not edit by hand.",
          "Design source: [Persistence](../architecture/PERSISTENCE.md). Target: PostgreSQL 18.", "",
          "| Migration | Name | Scope |", "| --- | --- | --- |",
          *[f"| {m.version:03d} | {m.name} | {'PostgreSQL only, opt-in' if m.opt_in else 'all dialects'} |" for m in MIGRATIONS], "",
          "## DDL (PostgreSQL 18)", "", "```sql", render_ddl(POSTGRES).rstrip("\n"), "```", ""]
    return "\n".join(md)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        ok = OUT.exists() and OUT.read_text() == text
        print(f"{'OK' if ok else 'FAIL'}: persistence schema doc {'current' if ok else 'stale'}")
        if not ok:
            print("Run: python3 scripts/gen_persistence_docs.py")
        return 0 if ok else 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
