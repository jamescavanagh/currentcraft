"""Generate six-type reference; --schema emits combined JSON Schema."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
from typing import Union
from pydantic import TypeAdapter

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from app.domain.operand.types import CONTRACTS as DOMAIN
from app.application.feature_graph.domain_types import CONTRACTS as APPLICATION

CONTRACTS = DOMAIN + APPLICATION
OUT = ROOT / "docs/contracts/SIX_DOMAIN_TYPES.md"


def schema():
    return TypeAdapter(Union[CONTRACTS]).json_schema()


def render():
    digest = hashlib.sha256(json.dumps(schema(), sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    lines = ["---", "title: Six concrete domain types (generated)", "tags: [currentcraft, generated]", "---", "",
        "# Six concrete domain types (generated)", "", "Generated by `scripts/gen_six_type_docs.py`; do not edit by hand.",
        "Design: [Six concrete domain types](../domain/SIX_DOMAIN_TYPES.md).", "",
        "Only new/overridden fields are listed; inherited fields remain in the full schema.",
        "Canonical fields: [Agency contracts](AGENCY_CONTRACTS.md). New fields all have descriptions.",
        "Domain values are not public DTOs. Structural schema does not prove evidence truth or authority.",
        "Use `--schema` for the combined JSON Schema. Schema SHA-256: `" + digest + "`.", ""]
    for model in CONTRACTS:
        lines += ["## `" + model.__name__ + "`", "", (model.__doc__ or "").strip(), "",
            "| Field | Required | Description |", "| --- | --- | --- |"]
        for name, field in model.model_fields.items():
            if name not in model.__annotations__:
                continue
            if not field.description:
                raise ValueError("missing new field description: " + model.__name__ + "." + name)
            description = field.description
            lines += [f"| `{name}` | {'yes' if field.is_required() else 'no'} | {description} |"]
        lines += [""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--schema", action="store_true")
    args = parser.parse_args(argv)
    if args.schema:
        print(json.dumps(schema(), indent=2, sort_keys=True))
        return 0
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("STALE: six-type reference; run scripts/gen_six_type_docs.py")
            return 1
        print("OK: six-type reference")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
