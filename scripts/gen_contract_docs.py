"""Generate (or --check) the contract docs and JSON Schemas from the simulation contracts.

Usage (repo root):
    python3 scripts/gen_contract_docs.py           # write docs/contracts/
    python3 scripts/gen_contract_docs.py --check   # exit 1 if docs are stale (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from app.application.simulation import contracts as C  # noqa: E402

OUT = ROOT / "docs" / "contracts"


def _type(ann) -> str:
    import enum
    if isinstance(ann, type) and issubclass(ann, enum.Enum):
        return ann.__name__ + " (" + " / ".join(str(m.value) for m in ann) + ")"
    if isinstance(ann, type):
        return ann.__name__
    s = str(ann)
    for junk in ("typing.", "app.application.simulation.contracts.", "app.application.simulation.tensors.", "pydantic.types.",
                 "annotated_types."):
        s = s.replace(junk, "")
    s = s.replace("NoneType", "None").replace("Optional[", "Optional[")
    import re
    s = re.sub(r"Annotated\[(\w+), [^\]]*\]+", r"\1", s)
    s = re.sub(r"<class '([\w.]+)'>", lambda m: m.group(1).split(".")[-1], s)
    s = re.sub(r"<enum '(\w+)'>", r"\1", s)
    return s if len(s) < 80 else s[:77] + "..."


def _default(f) -> str:
    import enum
    if f.is_required():
        return "yes"
    if f.default_factory is not None:
        return f"no (`{f.default_factory.__name__}()`)"
    d = f.default
    if isinstance(d, enum.Enum):
        d = d.value
    return "no" if d is None else f"no (`{d!r}`)"


def _field_rows(model) -> list[str]:
    rows = []
    for name, f in model.model_fields.items():
        desc = (f.description or "").replace("|", "\\|")
        rows.append(f"| `{name}` | `{_type(f.annotation)}` | {_default(f)} | {desc} |")
    return rows


def render() -> dict[str, str]:
    files: dict[str, str] = {}
    md = ["# Simulation contracts (generated)", "",
          "Generated by `scripts/gen_contract_docs.py` from `src/app/application/simulation/contracts.py`.",
          "Do not edit by hand: change the contract, then regenerate. CI fails when this file is stale.", "",
          f"Schema version: `{C.SCHEMA_VERSION}`. Results are `embedding_geometry`: a procedural vortex field over embedded records,",
          "not CFD and not an operational forecast.", "",
          "Notation: lambda is inflow only. Jacobian eigenvalues are mu (`CriticalPoint.mu_min_abs`). "
          f"Legacy {', '.join('`' + v + '`' for v in C.LEGACY_SCHEMA_VERSIONS)} payloads still read: the version is upgraded on input "
          "and the pre-0.9.8 key `lambda_min_abs` is accepted, but output is always the current version with `mu_min_abs`.", "",
          "Layering: these models import Pydantic only. Arrays live in `app.infrastructure.tensors`; contracts carry `TensorRef`",
          "handles (spec, key, concrete shape, SHA-256). Symbols such as `N`, `S`, `G` must bind to one size per contract instance.", "",
          "## Tensor contracts", ""]
    for m in C.TENSOR_CONTRACTS:
        md += [f"### `{m.__name__}`", "", f"Produced by `{m.PRODUCED_BY}`. {(m.__doc__ or '').strip()}", "",
               "| Field | Tensor | Dims | Shape | dtype | Unit | Bounds | Meaning |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for fname, s in m.TENSORS.items():
            req = m.model_fields[fname].is_required()
            bounds = "" if s.min_value is None and s.max_value is None else f"[{s.min_value if s.min_value is not None else '-inf'}, {s.max_value if s.max_value is not None else 'inf'}]"
            md.append(f"| `{fname}`{'' if req else ' (optional)'} | `{s.name}` | {', '.join(s.dims)} | ({', '.join(map(str, s.shape))}) | {s.dtype} | {s.unit or ''} | {bounds} | {s.description.replace('|', '/')} |")
        md += ["", "| Field | Type | Required | Description |", "| --- | --- | --- | --- |", *_field_rows(m), ""]
    md += ["## Request and value models", ""]
    for m in C.CONTRACTS:
        if m in C.TENSOR_CONTRACTS:
            continue
        md += [f"### `{m.__name__}`", "", (m.__doc__ or "").strip(), "", "| Field | Type | Required | Description |",
               "| --- | --- | --- | --- |", *_field_rows(m), ""]
    md += ["## Feature orders", "", "GNN node features (`GraphSample.x`, axis `feature`): " + ", ".join(f"`{f}`" for f in C.NODE_FEATURES) + ".",
           "`nearest_saddle_distance` is -1 when no saddle exists at that inflow.", "",
           "GNN edge features (`GraphSample.edge_attr`): " + ", ".join(f"`{f}`" for f in C.EDGE_FEATURES) + ". Edge j -> i carries k_ij (j's influence on i).", "",
           "Field channels (`field`, `cnn.x`): " + ", ".join(f"`{c}`" for c in C.FIELD_CHANNELS) + ".", "",
           "## JSON Schemas", "", *[f"- [`{m.__name__}`](schemas/{m.__name__}.schema.json)" for m in C.CONTRACTS], ""]
    files["SIMULATION_CONTRACTS.md"] = "\n".join(md)
    for m in C.CONTRACTS:
        files[f"schemas/{m.__name__}.schema.json"] = json.dumps(m.model_json_schema(), indent=2, sort_keys=True) + "\n"
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    files, stale = render(), []
    for rel, text in files.items():
        path = OUT / rel
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if a.check:
        extra = sorted(str(p.relative_to(OUT)) for p in (OUT / "schemas").glob("*.json") if str(p.relative_to(OUT)) not in files)
        for rel in stale:
            print(f"STALE {rel}")
        for rel in extra:
            print(f"ORPHAN {rel}")
        print(f"{'OK' if not stale and not extra else 'FAIL'}: {len(files)} generated docs, {len(stale)} stale, {len(extra)} orphan")
        if stale or extra:
            print("Run: python3 scripts/gen_contract_docs.py")
        return 1 if stale or extra else 0
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
