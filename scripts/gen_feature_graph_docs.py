"""Generate the six-domain reference; --schema emits its combined JSON Schema."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
from typing import Union

from pydantic import TypeAdapter

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from app.domain.operand.profile import CONTRACTS as REFERENCES
from app.domain.operand.feature_graph import CONTRACTS as GRAPH
from app.application.feature_graph.contracts import CONTRACTS as ANALYSIS

CONTRACTS = REFERENCES + GRAPH + ANALYSIS
OUT = ROOT / "docs/contracts/FEATURE_GRAPH_CONTRACTS.md"


def schema():
    return TypeAdapter(Union[CONTRACTS]).json_schema()


def render():
    encoded = json.dumps(schema(), sort_keys=True, separators=(",", ":"))
    lines = ["---", "title: Six-domain feature contracts (generated)", "tags: [currentcraft, generated]", "---", "",
        "# Six-domain feature contracts (generated)", "",
        "Generated by `scripts/gen_feature_graph_docs.py`; do not edit by hand.",
        "Design: [six-domain evidence and versioned feature graph](../pipelines/OPERAND_COMPRESSION.md).", "",
        "Run the generator with `--schema` for the combined JSON Schema. Structural schema",
        "does not prove cross-record validity, evidence truth, physical compatibility or authority.", "",
        "Schema SHA-256: `" + hashlib.sha256(encoded.encode()).hexdigest() + "`.", ""]
    for model in CONTRACTS:
        lines += ["## `" + model.__name__ + "`", "", (model.__doc__ or "").strip(), "",
                  "| Field | Required | Description |", "| --- | --- | --- |"]
        for name, field in model.model_fields.items():
            if not field.description:
                raise ValueError("missing field description: " + model.__name__ + "." + name)
            lines += [f"| `{name}` | {'yes' if field.is_required() else 'no'} | {field.description} |"]
        lines += [""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--schema", action="store_true")
    args = parser.parse_args(argv)
    if args.schema:
        print(json.dumps(schema(), indent=2, sort_keys=True))
        return 0
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("STALE: six-domain feature contracts; run scripts/gen_feature_graph_docs.py")
            return 1
        print("OK: six-domain feature contract reference")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
