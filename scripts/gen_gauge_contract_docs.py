"""Generate (or --check) the gauge contract docs. Mirrors scripts/gen_contract_docs.py for the gauge slice."""

from __future__ import annotations

import argparse
import enum
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from app.application.gauge import contracts as G  # noqa: E402
from app.application.gauge import geodesic as GP
from app.application.gauge import winding as VW
CONTRACTS = G.CONTRACTS + GP.CONTRACTS + VW.CONTRACTS
TENSOR_CONTRACTS = G.TENSOR_CONTRACTS + GP.TENSOR_CONTRACTS

OUT = ROOT / "docs" / "contracts"
JUNK = ("typing.", "app.application.gauge.contracts.", "app.application.simulation.contracts.",
        "app.application.simulation.tensors.", "pydantic.types.", "annotated_types.")


def _type(ann) -> str:
    if isinstance(ann, type) and issubclass(ann, enum.Enum):
        return ann.__name__ + " (" + " / ".join(str(m.value) for m in ann) + ")"
    if isinstance(ann, type):
        return ann.__name__
    s = str(ann)
    for junk in JUNK:
        s = s.replace(junk, "")
    s = s.replace("NoneType", "None")
    s = re.sub(r"Annotated\[(\w+), [^\]]*\]+", r"\1", s)
    s = re.sub(r"<class '([\w.]+)'>", lambda m: m.group(1).split(".")[-1], s)
    s = re.sub(r"<enum '(\w+)'>", r"\1", s)
    return s if len(s) < 80 else s[:77] + "..."


def _default(f) -> str:
    if f.is_required():
        return "yes"
    if f.default_factory is not None:
        return f"no (`{f.default_factory.__name__}()`)"
    d = f.default
    if isinstance(d, enum.Enum):
        d = d.value
    return "no" if d is None else f"no (`{d!r}`)"


def _rows(model) -> list[str]:
    return [f"| `{n}` | `{_type(f.annotation)}` | {_default(f)} | {(f.description or '').replace('|', '/')} |"
            for n, f in model.model_fields.items()]


def _tensor_rows(specs, required=lambda n: True) -> list[str]:
    out = ["| Field | Tensor | Dims | Shape | dtype | Unit | Bounds | Meaning |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for fname, s in specs.items():
        bounds = "" if s.min_value is None and s.max_value is None else f"[{s.min_value if s.min_value is not None else '-inf'}, {s.max_value if s.max_value is not None else 'inf'}]"
        out.append(f"| `{fname}`{'' if required(fname) else ' (optional)'} | `{s.name}` | {', '.join(s.dims)} | ({', '.join(map(str, s.shape))}) | {s.dtype} | {s.unit or ''} | {bounds} | {s.description.replace('|', '/')} |")
    return out


def render() -> dict[str, str]:
    md = ["# Gauge contracts (generated)", "",
          "Generated by `scripts/gen_gauge_contract_docs.py` from `src/app/application/gauge/contracts.py`.",
          "Do not edit by hand: change the contract, then regenerate. CI fails when this file is stale.", "",
          f"Schema version: `{G.SCHEMA_VERSION}`. Results are `embedding_geometry`: a lattice-gauge reading of reduced embeddings,",
          "not an operational forecast. Gauges are read-only measurements and are not GNN inputs.", "",
          "Layering: Pydantic only. Arrays live in `app.infrastructure.gauge` and the shared `InMemoryNumpyTensorStore`;",
          "contracts carry `TensorRef` handles. `TensorContract`, `NodeRole`, `TensorSpec` and `TensorRef` are the simulation slice's own classes.", "",
          "## Gauge vs measurement", "",
          "Gauge-dependent (change under a frame rotation, never measurements): " + ", ".join(f"`{n}`" for n in G.GaugeResult.GAUGE_DEPENDENT) + ".",
          "Gauge-invariant (measurements): " + ", ".join(f"`{n}`" for n in G.GaugeResult.invariant_tensors()) + ", and `loops`.", "",
          "## Input tensors", "", *_tensor_rows(G.INPUT_TENSORS), "",
          "## Tensor contracts", ""]
    for m in TENSOR_CONTRACTS:
        md += [f"### `{m.__name__}`", "", f"Produced by `{m.PRODUCED_BY}`. {(m.__doc__ or '').strip()}", "",
               *_tensor_rows(m.TENSORS, lambda n, m=m: m.model_fields[n].is_required()), "",
               "| Field | Type | Required | Description |", "| --- | --- | --- | --- |", *_rows(m), ""]
    md += ["## Request and value models", ""]
    for m in CONTRACTS:
        if m in TENSOR_CONTRACTS:
            continue
        md += [f"### `{m.__name__}`", "", (m.__doc__ or "").strip(), "", "| Field | Type | Required | Description |",
               "| --- | --- | --- | --- |", *_rows(m), ""]
    md += ["## Operand gauge features", "", "Column order of `GaugeResult.node_gauges` (axis `feature`):", "",
           "| # | Feature | Meaning |", "| --- | --- | --- |",
           *[f"| {i} | `{f}` | {G.NODE_GAUGE_MEANINGS[f]} |" for i, f in enumerate(G.NODE_GAUGE_FEATURES)], "",
           "## JSON Schemas", "", *[f"- [`{m.__name__}`](schemas/gauge/{m.__name__}.schema.json)" for m in CONTRACTS], ""]
    files = {"GAUGE_CONTRACTS.md": "\n".join(md)}
    for m in CONTRACTS:
        files[f"schemas/gauge/{m.__name__}.schema.json"] = json.dumps(m.model_json_schema(), indent=2, sort_keys=True) + "\n"
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    files, stale = render(), []
    for rel, text in files.items():
        path = OUT / rel
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if a.check:
        extra = sorted(str(p.relative_to(OUT)) for p in (OUT / "schemas" / "gauge").glob("*.json") if str(p.relative_to(OUT)) not in files)
        for rel in stale:
            print(f"STALE {rel}")
        for rel in extra:
            print(f"ORPHAN {rel}")
        print(f"{'OK' if not stale and not extra else 'FAIL'}: {len(files)} generated gauge docs, {len(stale)} stale, {len(extra)} orphan")
        if stale or extra:
            print("Run: python3 scripts/gen_gauge_contract_docs.py")
        return 1 if stale or extra else 0
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
