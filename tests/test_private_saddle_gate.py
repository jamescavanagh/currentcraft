FAILURE = "Private saddle acceptance failed; inspect evidence in the private environment"


def canonical_digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                     allow_nan=False).encode()).hexdigest()


def external_file(name):
    path = Path(name).resolve(strict=True)
    if path.is_relative_to(ROOT) or not path.is_file() or path.stat().st_size > 10_000_000:
        raise ValueError
    return path


def load_case(name):
    """Internal case envelope, not a registered runtime ingestion contract.

    Source JSON is a NodeInteractionRequest. References are separately pinned,
    never generated by this runner. The external coordinator supplies both.
    """
    case = json.loads(external_file(name).read_bytes())
    if case["version"] != "private-saddle-acceptance/v1":
        raise ValueError
    if not re.fullmatch(r"[0-9a-f]{40}", case["baseline_revision"]):
        raise ValueError
    provenance = case["provenance"]
    for key in ("source_version", "method", "run_reference", "approval_reference"):
        if not isinstance(provenance[key], str) or not provenance[key].strip():
            raise ValueError
    if not re.fullmatch(r"[0-9a-f]{64}", provenance["mapping_sha256"]):
        raise ValueError
    raw = external_file(case["source_file"]).read_bytes()
    if hashlib.sha256(raw).hexdigest() != case["source_sha256"]:
        raise ValueError
    req = C.NodeInteractionRequest.model_validate_json(raw)
    reference = case["reference"]
    if canonical_digest(reference) != case["reference_sha256"]:
        raise ValueError
    slices, events = reference["slices"], reference["events"]
    if not slices or len(slices) != len(req.inflow.values):
        raise ValueError
    if reference["expected_slices"] != len(slices):
        raise ValueError
    expected = reference["expected_saddle_labels"]
    if isinstance(expected, bool) or not isinstance(expected, int) or expected < 1:
        raise ValueError
    if sum(len(s["points"]) for s in slices) != expected:
        raise ValueError
    for inflow, sl in zip(req.inflow.values, slices):
        if sl["inflow"] != inflow:
            raise ValueError
        for point in sl["points"]:
            if point["kind"] != "saddle" or not all(math.isfinite(point[k]) for k in ("x", "y")):
                raise ValueError
        # Duplicate labels would make recovery counts misleading.
        for i, p in enumerate(sl["points"]):
            if any(math.hypot(p["x"] - q["x"], p["y"] - q["y"]) < 1e-3
                   for q in sl["points"][i + 1:]):
                raise ValueError
    if len(events) != reference["expected_events"] or not events:
        raise ValueError
    for event in events:
        if not math.isfinite(event["inflow"]) or not req.inflow.values[0] <= event["inflow"] <= req.inflow.values[-1]:
            raise ValueError
        for key in ("saddles_before", "saddles_after"):
            if type(event[key]) is not int or event[key] < 0:
                raise ValueError
        if event["saddles_before"] == event["saddles_after"]:
            raise ValueError
    if any(b["inflow"] <= a["inflow"] for a, b in zip(events, events[1:])):
        raise ValueError
    return req, reference


def run_case(req, reference):
    solve = K.critical_points
    service, store, _ = build_numpy_simulation()
    reverse = req.model_dump()
    reverse["nodes"] = tuple(reversed(reverse["nodes"]))
    shuffled = C.NodeInteractionRequest.model_validate(reverse)
    if req.digest() != shuffled.digest():
        raise ValueError
    matched = 0
    for seeds in seed_ensemble():
        def seeded(*args, **kwargs):
            kwargs["seed_points"] = seeds
            return solve(*args, **kwargs)

        with patch.object(K, "critical_points", side_effect=seeded):
            result = service.interactions.simulate(req)
            other = service.interactions.simulate(shuffled)
        if result.slices != other.slices or result.events != other.events:
            raise ValueError
        for field in ("coupling", "node_velocity", "field"):
            a, b = getattr(result, field), getattr(other, field)
            if (a is None) != (b is None) or (a is not None and not (store.get(a) == store.get(b)).all()):
                raise ValueError
        if len(result.slices) != len(reference["slices"]):
            raise ValueError
        for ref, sl in zip(reference["slices"], result.slices):
            observed = [p.model_dump() for p in sl.points if p.kind == C.PointKind.SADDLE]
            if sl.inflow != ref["inflow"] or not roots_match(ref["points"], observed):
                raise ValueError
            matched += len(observed)
        if len(result.events) != len(reference["events"]):
            raise ValueError
        for ref, event in zip(reference["events"], result.events):
            if (ref["saddles_before"], ref["saddles_after"]) != (event.saddles_before, event.saddles_after):
                raise ValueError
            if abs(ref["inflow"] - event.inflow) > 1e-4:
                raise ValueError
    if matched != reference["expected_saddle_labels"] * 35:
        raise ValueError
    return {"seedings": 35, "node_orders": 2, "matched_labels": matched}


class PrivateGateControls(unittest.TestCase):
    def test_synthetic_runner_executes_every_seeding_and_both_orders(self):
        req = C.NodeInteractionRequest(
            frame_id="synthetic-private-runner-control", grid=None,
            nodes=(C.InteractionNode(id="v0", x=0, y=0, strength=1),),
            inflow=C.InflowSweep(values=(0, 0.1)))
        # This is a mock protocol/control-flow test, not numerical acceptance.
        from types import SimpleNamespace
        point = SimpleNamespace(kind=C.PointKind.SADDLE,
                                model_dump=lambda: {"x": 0, "y": 0, "kind": "saddle"})
        result = SimpleNamespace(
            slices=(SimpleNamespace(inflow=0, points=(point,)),
                    SimpleNamespace(inflow=0.1, points=())),
            events=(SimpleNamespace(inflow=0.05, saddles_before=1, saddles_after=0),),
            coupling=None, node_velocity=None, field=None)
        reference = {"expected_saddle_labels": 1,
                     "slices": [{"inflow": 0, "points": [point.model_dump()]},
                                {"inflow": 0.1, "points": []}],
                     "events": [{"inflow": 0.05, "saddles_before": 1, "saddles_after": 0}]}
        with patch(__name__ + ".build_numpy_simulation") as wiring:
            service = wiring.return_value
            wiring.return_value = (service, None, None)
            simulate = service.interactions.simulate
            simulate.return_value = result
            summary = run_case(req, reference)
        self.assertEqual(simulate.call_count, 70)
        self.assertEqual(summary, {"seedings": 35, "node_orders": 2, "matched_labels": 35})

    def test_in_checkout_source_is_rejected(self):
        with self.assertRaises(ValueError):
            external_file(ROOT / "pyproject.toml")

    def test_incorrect_source_digest_is_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            source, envelope = Path(tmp) / "source.json", Path(tmp) / "case.json"
            source.write_text("{}")
            envelope.write_text(json.dumps({
                "version": "private-saddle-acceptance/v1",
                "baseline_revision": "a" * 40,
                "provenance": {"source_version": "synthetic", "method": "synthetic",
                               "run_reference": "synthetic", "approval_reference": "synthetic",
                               "mapping_sha256": "b" * 64},
                "source_file": str(source), "source_sha256": "c" * 64,
            }))
            with self.assertRaises(ValueError):
                load_case(envelope)

    def test_canonical_digest_is_order_independent_and_content_sensitive(self):
        self.assertEqual(canonical_digest({"a": 1, "b": 2}), canonical_digest({"b": 2, "a": 1}))
        self.assertNotEqual(canonical_digest({"a": 1}), canonical_digest({"a": 2}))


class PrivateSaddleAcceptance(unittest.TestCase):
    def test_private_seed_and_order_gate(self):
        name = os.environ.get("DATAMESH_PRIVATE_SADDLE_CASE")
        if not name:
            if os.environ.get("DATAMESH_REQUIRE_PRIVATE_SADDLE") == "1":
                self.fail("Private saddle acceptance is required but not configured")
            self.skipTest("Private saddle acceptance not configured; not acceptance evidence")
        # Keep upstream tracebacks/validation messages out of public test output.
        failed = False
        try:
            req, reference = load_case(name)
            run_case(req, reference)
        except Exception:
            failed = True
        if failed:
            self.fail(FAILURE)


