SCHEMA_VERSION = "currentcraft-six-types/v1"
Revision = Annotated[int, Field(ge=1, strict=True)]
TypeSchema = Literal["currentcraft-six-types/v1"]
Outcome = Literal["not_run", "pass", "fail", "inconclusive"]


def record_ref(record: VersionedEntity) -> VersionRef:
    return VersionRef(identity=record.entity_id, version=record.record_version)


def distinct_refs(values, label):
    identities = [ref.identity for ref in values]
    if len(set(identities)) != len(identities):
        raise ValueError("duplicate_or_conflicting_" + label)


def selection_digest(selected) -> str:
    encoded = json.dumps(sorted(str(key) for key in selected), separators=(",", ":"))
    return hashlib.sha256(encoded.encode()).hexdigest()


class ConfigurationBinding(FrozenValue):
    """Exact configuration object and model pin, not permission or compatibility proof."""
    configuration: VersionRef = Field(description="Exact configuration entity identity and record version.")
    graph_id: UUID = Field(description="Exact feature-model graph identity.")
    graph_revision: Revision = Field(description="Exact selected graph revision.")
    graph_digest: Digest = Field(description="Exact selected graph content digest.")
    selection_digest: Digest = Field(description="Canonical selected-feature identity digest, not source text.")


class RevisionAuthorization(FrozenValue):
    """Sourced authorization assertion; actor authority must be resolved separately."""
    revision: VersionRef = Field(description="Exact source revision this assertion concerns.")
    decision: VersionRef = Field(description="Exact external release decision record, not generated by receipt.")
    evidence: tuple[VersionRef, ...] = Field(min_length=1, description="Exact supporting evidence references.")

    @model_validator(mode="after")
    def evidence_integrity(self):
        distinct_refs(self.evidence, "authorization_evidence")
        return self


class ProjectType(Project):
    """Project-specific scope and baseline without replacing the canonical identity."""
    schema_version: TypeSchema = Field(default=SCHEMA_VERSION, description="Independent six-type wire family; no implicit legacy upgrade.")
    scope: Fact[Text] = Field(default_factory=unknown, description="Sourced scope or explicit unknown; not an executable work authorization.")
    lifecycle_phase: Fact[Text] = Field(default_factory=unknown, description="Sourced phase label; no universal phase policy imposed.")
    work_packages: tuple[VersionRef, ...] = Field(default=(), description="Exact supplied work-package links; empty does not establish that no packages exist.")
    dependencies: tuple[VersionRef, ...] = Field(default=(), description="Explicit exact dependencies, not inferred from sequence.")
    configuration_baseline: Fact[ConfigurationBinding] = Field(default_factory=unknown, description="Selected exact baseline or explicit unknown, not approval.")

    @model_validator(mode="after")
    def project_integrity(self):
        for label in ("work_packages", "dependencies"):
            values = getattr(self, label)
            distinct_refs(values, label)
            if any(ref.identity == self.entity_id for ref in values):
                raise ValueError("project_self_reference")
        return self


class WorkingDocumentType(Document):
    """Working-document revision lineage; receipt and authorization are independent."""
    schema_version: TypeSchema = Field(default=SCHEMA_VERSION, description="Independent six-type wire family.")
    project_revision: Revision = Field(description="Exact canonical project record version, paired with project_id.")
    captured_revision: VersionRef = Field(description="Exact source revision represented by this document snapshot.")
    configuration: Fact[ConfigurationBinding] = Field(default_factory=unknown, description="Configuration evidenced by this source revision, or explicit unknown.")
    derived_from: tuple[VersionRef, ...] = Field(default=(), description="Exact source revisions used to derive this revision.")
    supersedes: Fact[VersionRef] = Field(default_factory=unknown, description="Sourced superseded revision, not inferred from timestamps or filename.")
    latest_received_revision: Fact[VersionRef] = Field(default_factory=unknown, description="Latest evidenced receipt; does not replace authorized revision.")
    authorization: Fact[RevisionAuthorization] = Field(default_factory=unknown, description="Independent sourced release assertion; not authority verification.")

    @model_validator(mode="after")
    def document_integrity(self):
        distinct_refs(self.derived_from, "derivation")
        if self.captured_revision in self.derived_from or self.supersedes.value == self.captured_revision:
            raise ValueError("document_revision_self_reference")
        return self


